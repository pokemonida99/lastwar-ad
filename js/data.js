// 一關的寫法：rows 由近到遠排，每一列是下面其中一種
//   ['左門', '右門']        整排兩個門
//   ['單門']                單一門，另一邊自動放陷阱（尖刺、坑洞輪流）
//   { horde: 30, x: 0 }     殭屍群
//   { spikes: 0 } / { holes: 3 }   在 x 位置放陷阱
// boss 是 Boss 血量，escort 是 Boss 前面的護衛殭屍
function level(name, start, boss, rows, escort = 0) {
  const items = [];
  let z = 16, side = -1, trap = 0;
  for (const r of rows) {
    if (Array.isArray(r) && r.length === 2) {
      items.push({ z, type: 'gates', left: r[0], right: r[1] });
      z += 18;
    } else if (Array.isArray(r)) {
      items.push({ z, type: 'gate', x: side * 3, w: 5.6, f: r[0] });
      items.push({ z: z - 2, type: trap++ % 2 ? 'holes' : 'spikes', x: -side * 3.2, w: 5, d: 4.5 });
      side = -side;
      z += 18;
    } else if (r.horde) {
      z += 4;
      items.push({ z, type: 'horde', x: r.x || 0, n: r.horde });
      z += 20;
    } else if ('spikes' in r || 'holes' in r) {
      const kind = 'spikes' in r ? 'spikes' : 'holes';
      items.push({ z, type: kind, x: r[kind], w: r.w || 4, d: 4.5 });
      z += 14;
    }
  }
  z += 8;
  items.push({ z, type: 'boss', x: 0, hp: boss, n: escort });
  return { name, start, length: z + 12, items };
}

